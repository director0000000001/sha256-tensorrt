"""Build (warped, truth) pairs to train the refiner on, out of the avatar's own clips.

**The problem this solves is that there is no ground truth.** The refiner's job
is to correct what the warp gets wrong, so it needs pairs of *what the warp
produced* and *what should have been there* -- and the avatar is a generated
person. No camera ever filmed them doing what the owner does, so for a live
frame the right answer does not exist and never will.

It does exist inside one clip. Every clip in ``avatars/*/frames`` is that same
face moving, so for any two frames A and B of one clip:

*   warp **A** onto **B**'s mesh, exactly as ``_warp_onto`` warps the avatar
    onto the driver's, and
*   **B itself is the answer** -- a real photograph of that face in that pose,
    with that expression, under that light.

The input carries the artefacts the warp actually makes (sheared triangles,
stretched lids, a mouth interior invented out of neighbouring skin) and the
target carries none of them. That is the whole training signal, and it is honest
because nothing in the pair is generated by us.

**The warp here is the shipped warp.** Same ``warp_mesh``, same triangulation
over the same ``MESH_INDICES``, same crop-to-the-face-box, so what the refiner
learns to undo is what the engine will hand it. A pair built from a prettier or
simpler warp would train a refiner for an engine that does not exist.

**The mask travels with the pair** because the loss must not be computed on the
background: outside the face the warp has no opinion, the two images differ by
the whole scene, and a refiner scored on that would spend its capacity there.

Pair selection is deterministic -- fixed frame offsets, no randomness -- so a
dataset can be rebuilt exactly. The offsets are spread on purpose: neighbouring
frames give a warp that is almost the identity and teach nothing, distant ones
give a severe warp, and the range in between is where the owner's face lives.

Usage::

    uv run python scripts/make_training_pairs.py --limit 200 --out data/pairs-v1
    uv run python scripts/make_training_pairs.py --size 256
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from extract_avatar_frames import sharpness_of, timestamp_of  # noqa: E402

from sha256.avatar.engine_warp import (  # noqa: E402
    _destination_mask,
    _pixel_points,
    _triangulate,
    _trim_forehead,
    warp_mesh,
)
from sha256.core.enums import PixelFormat  # noqa: E402
from sha256.core.types import FrameMetadata, VideoFrame  # noqa: E402
from sha256.tracking.mediapipe_tracker import (  # noqa: E402
    DEFAULT_MODEL_RELATIVE_PATH,
    MediaPipeFaceTracker,
)

# The tile the refiner sees. 256 is what B001 measured the portrait-shaped
# workload at -- 1.83 ms fp32, 1.33 ms fp16 -- against a 33.3 ms frame budget,
# so it is the size the whole plan is costed on.
DEFAULT_SIZE = 256

# How far apart a pair's two frames are, in frames. Spread rather than uniform:
# at 2 frames the warp is nearly the identity and there is nothing to correct,
# at 120 it is a different pose entirely. Both directions, so a rung is not
# only ever warped forwards in time.
DEFAULT_OFFSETS = (-120, -45, -15, -5, 5, 15, 45, 120)

# A face smaller than this is not worth a tile: the pair would be upscaled into
# the 256 box and the refiner would learn to sharpen, which is not its job.
DEFAULT_MIN_FACE = 300.0

# Below this a frame is smeared, and a smeared *target* teaches the refiner to
# produce smear. The floor matters more here than in a ladder builder, where a
# soft rung is merely a soft rung.
DEFAULT_MIN_SHARPNESS = 40.0


@dataclass(frozen=True)
class Frame:
    """One usable frame of a clip, with everything a pair needs from it."""

    index: int
    path: Path
    image: np.ndarray
    mesh: np.ndarray
    """``MESH_INDICES`` in this image's pixels."""

    face_width: float
    sharpness: float


def read_clip(folder: Path, model: Path, min_face: float, min_sharpness: float) -> list[Frame]:
    """Every usable frame of one clip, tracked in sequence.

    In sequence and with the real timestamp, which is not a detail: the tracker
    runs in video mode and carries a prior between frames, and handing it stills
    at one timestamp made it report its own lag instead of the face. That is
    what built the eye ladder out of nothing on 2026-08-21.
    """
    import cv2

    paths = sorted(folder.glob("*.jpg")) + sorted(folder.glob("*.png"))
    if not paths:
        return []

    tracker = MediaPipeFaceTracker(model_path=model)
    tracker.start()
    frames: list[Frame] = []
    try:
        for index, path in enumerate(paths):
            image = cv2.imread(str(path))
            if image is None:
                continue
            result = tracker.process(
                VideoFrame(
                    data=np.ascontiguousarray(image),
                    pixel_format=PixelFormat.BGR24,
                    metadata=FrameMetadata(
                        frame_id=index, capture_timestamp=timestamp_of(path, index)
                    ),
                )
            )
            if not result.face_detected or result.landmarks is None:
                continue

            height, width = image.shape[:2]
            mesh = _pixel_points(result.landmarks.points, width, height)
            if mesh is None:
                continue

            points = result.landmarks.points
            face_width = float(points[:, 0].max() - points[:, 0].min()) * width
            sharpness = sharpness_of(image, points)
            if face_width < min_face or sharpness < min_sharpness:
                continue

            frames.append(
                Frame(
                    index=index,
                    path=path,
                    image=image,
                    mesh=mesh,
                    face_width=face_width,
                    sharpness=sharpness,
                )
            )
    finally:
        tracker.stop()
    return frames


def square_box(mesh: np.ndarray, width: int, height: int, pad: int = 8) -> tuple[int, int, int]:
    """The face's box, squared, as ``(x0, y0, side)`` or a zero side.

    Taken from the mask's outline as well as the landmarks, the way
    ``_warp_onto`` takes it, because the mask reaches below the jaw and a box
    sized on landmarks alone cuts it off. Squared because the tile is square and
    a non-square box resized into it would stretch the face -- and the refiner
    would then have to learn the stretch as well as the artefacts.
    """
    outline = _trim_forehead(mesh)
    x0 = int(min(mesh[:, 0].min(), outline[:, 0].min())) - pad
    y0 = int(min(mesh[:, 1].min(), outline[:, 1].min())) - pad
    x1 = int(max(mesh[:, 0].max(), outline[:, 0].max())) + pad
    y1 = int(max(mesh[:, 1].max(), outline[:, 1].max())) + pad

    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    bx0, by0 = cx - side // 2, cy - side // 2

    # Clipped rather than shifted: shifting a box that runs off the frame moves
    # the face off centre, and every tile has to frame the face the same way or
    # the refiner sees the framing as part of the problem.
    if bx0 < 0 or by0 < 0 or bx0 + side > width or by0 + side > height or side < 2:
        return 0, 0, 0
    return bx0, by0, side


@dataclass
class Pair:
    clip: str
    source_frame: int
    target_frame: int
    offset: int
    residual: float
    """Mean absolute difference inside the mask, 0-255. How much there is to fix."""

    worst: float
    """The 99th percentile of the same difference -- where the artefacts are."""


def build_pair(
    source: Frame, target: Frame, size: int
) -> tuple[np.ndarray, np.ndarray, np.ndarray, float, float] | None:
    """One (warped, truth, mask, residual, worst), or ``None`` if the box misses."""
    import cv2

    height, width = target.image.shape[:2]
    bx0, by0, side = square_box(target.mesh, width, height)
    if side == 0:
        return None

    local = (target.mesh - (bx0, by0)).astype(np.float32)
    triangles = _triangulate(source.mesh, source.image.shape[1], source.image.shape[0])

    warped = warp_mesh(source.image, source.mesh, local, triangles, side, side)
    truth = np.ascontiguousarray(target.image[by0 : by0 + side, bx0 : bx0 + side])

    alpha = _destination_mask(local, side, side)
    mask = np.asarray(alpha, dtype=np.float32)
    if mask.ndim == 3:
        mask = mask[..., 0]

    # Resized after the warp, not before: warping at the tile's resolution would
    # measure the artefacts of a small warp, and the engine warps at the face's
    # own size. INTER_AREA down, which is what every other downscale in this
    # project uses.
    warped_t = cv2.resize(warped, (size, size), interpolation=cv2.INTER_AREA)
    truth_t = cv2.resize(truth, (size, size), interpolation=cv2.INTER_AREA)
    mask_t = cv2.resize(mask, (size, size), interpolation=cv2.INTER_AREA)

    inside = mask_t > 0.5
    if not bool(inside.any()):
        return None
    difference = np.abs(warped_t.astype(np.float32) - truth_t.astype(np.float32)).mean(axis=2)
    residual = float(difference[inside].mean())
    # The worst hundredth of the face as well as the average of it. A sheared
    # triangle by the inner eye corner is a handful of pixels that are wrong by
    # a lot, and it moves the mean by almost nothing -- so a dataset judged on
    # the mean alone could be full of exactly the defect the owner reports and
    # look mild.
    worst = float(np.percentile(difference[inside], 99))

    return warped_t, truth_t, (mask_t * 255.0).astype(np.uint8), residual, worst


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--frames",
        type=Path,
        default=REPO_ROOT / "avatars" / "my_avatar" / "frames",
        help="Directory of dumped clip folders.",
    )
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "data" / "pairs-v1")
    parser.add_argument("--size", type=int, default=DEFAULT_SIZE)
    parser.add_argument("--min-face", type=float, default=DEFAULT_MIN_FACE)
    parser.add_argument("--min-sharpness", type=float, default=DEFAULT_MIN_SHARPNESS)
    parser.add_argument("--stride", type=int, default=1, help="Use every Nth frame as a target.")
    parser.add_argument("--limit", type=int, default=None, help="Stop after this many pairs.")
    parser.add_argument(
        "--offsets",
        type=int,
        nargs="+",
        default=list(DEFAULT_OFFSETS),
        help="Frame distances from the target to take the source from.",
    )
    args = parser.parse_args(argv)

    model = REPO_ROOT / "models" / DEFAULT_MODEL_RELATIVE_PATH
    if not model.is_file():
        print(f"Model bundle missing: {model}")
        return 1

    folders = sorted(p for p in args.frames.iterdir() if p.is_dir())
    if not folders:
        print(f"No clip folders under {args.frames}")
        return 1

    args.out.mkdir(parents=True, exist_ok=True)
    warped_all: list[np.ndarray] = []
    truth_all: list[np.ndarray] = []
    mask_all: list[np.ndarray] = []
    index: list[Pair] = []
    stop = False

    for folder in folders:
        frames = read_clip(folder, model, args.min_face, args.min_sharpness)
        if len(frames) < 2:
            print(f"{folder.name:<14} {len(frames):>4} usable -- too few for a pair", flush=True)
            continue

        by_index = {frame.index: frame for frame in frames}
        made = 0
        for target in frames[:: args.stride]:
            for offset in args.offsets:
                source = by_index.get(target.index + offset)
                if source is None:
                    continue
                built = build_pair(source, target, args.size)
                if built is None:
                    continue
                warped, truth, mask, residual, worst = built
                warped_all.append(warped)
                truth_all.append(truth)
                mask_all.append(mask)
                index.append(
                    Pair(
                        clip=folder.name,
                        source_frame=source.index,
                        target_frame=target.index,
                        offset=offset,
                        residual=residual,
                        worst=worst,
                    )
                )
                made += 1
                if args.limit is not None and len(index) >= args.limit:
                    stop = True
                    break
            if stop:
                break

        print(f"{folder.name:<14} {len(frames):>4} usable  {made:>5} pairs", flush=True)
        if stop:
            print("(stopped at --limit)")
            break

    if not index:
        print("\nNo pairs were built.")
        return 1

    dataset = args.out / "pairs.npz"
    np.savez_compressed(
        dataset,
        warped=np.stack(warped_all),
        truth=np.stack(truth_all),
        mask=np.stack(mask_all),
    )
    (args.out / "index.json").write_text(
        json.dumps(
            {
                "size": args.size,
                "offsets": args.offsets,
                "min_face": args.min_face,
                "min_sharpness": args.min_sharpness,
                "pairs": [p.__dict__ for p in index],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )

    residuals = sorted(p.residual for p in index)

    def q(p: float) -> float:
        return residuals[min(int(p * (len(residuals) - 1)), len(residuals) - 1)]

    megabytes = dataset.stat().st_size / (1024 * 1024)
    print(f"\n{len(index)} pairs at {args.size}x{args.size} -> {dataset} ({megabytes:.0f} MiB)")

    # What the dataset is made of, because a refiner can only learn to fix what
    # the pairs contain. A set whose residuals are all tiny teaches nothing; one
    # whose residuals are all huge teaches it to repair a warp the engine never
    # produces.
    print("\nwarp residual inside the mask, 0-255:")
    print(
        f"  mean of the face   p5 {q(0.05):.1f}   p25 {q(0.25):.1f}   p50 {q(0.5):.1f}   "
        f"p75 {q(0.75):.1f}   p95 {q(0.95):.1f}"
    )
    worst = sorted(p.worst for p in index)
    print(
        f"  worst 1% of it     p5 {worst[len(worst) // 20]:.1f}   "
        f"p50 {statistics.median(worst):.1f}   p95 {worst[-max(1, len(worst) // 20)]:.1f}"
    )

    print("\nby how far apart the two frames were:")
    print(f"{'offset':>8}{'pairs':>8}{'median mean':>14}{'median worst 1%':>18}")
    for offset in sorted({p.offset for p in index}):
        group = [p for p in index if p.offset == offset]
        print(
            f"{offset:>8}{len(group):>8}"
            f"{statistics.median(p.residual for p in group):>14.1f}"
            f"{statistics.median(p.worst for p in group):>18.1f}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
