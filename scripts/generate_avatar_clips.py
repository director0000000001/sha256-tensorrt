@dataclass(frozen=True)
class Verdict:
    """Whether a take is usable, in the terms the next decision needs.

    ``fatal`` separates "this clip is bad" from "this checkout is bad" — a
    missing model bundle or a role name that does not exist must stop the run,
    not buy another take of the same thing.
    """

    ok: bool
    facts: tuple[str, ...] = ()
    reasons: tuple[str, ...] = ()
    fatal: bool = False


def _judge_ladder(clip: Clip, report: dict[str, Any]) -> Verdict:
    ladder = report.get("ladder")
    if not ladder:
        return Verdict(False, reasons=("no ladder in the report — was --ladder passed?",))

    rungs = list(ladder["rungs"])
    if not rungs:
        return Verdict(False, reasons=("no usable frames at any angle",))

    wanted_sign = clip.expect_yaw_sign
    if wanted_sign == "positive":
        side = [rung for rung in rungs if float(rung["yaw"]) > 0]
    elif wanted_sign == "negative":
        side = [rung for rung in rungs if float(rung["yaw"]) < 0]
    else:
        side = rungs

    sharp = [rung for rung in side if not rung["blurred"]]
    reach = max((abs(float(rung["yaw"])) for rung in sharp), default=0.0)
    blurred_fraction = float(ladder["blurred"]) / len(rungs)

    facts = (
        f"{len(rungs)} rungs, {len(side)} on the requested side, {len(sharp)} of those sharp",
        f"sharp reach {reach:.0f} deg of yaw, whole clip "
        f"{float(ladder['yaw_min']):.0f}..{float(ladder['yaw_max']):.0f} deg",
        f"{blurred_fraction:.0%} of rungs motion blurred",
    )

    reasons: list[str] = []
    if wanted_sign != "any" and not side:
        turned = "their own left" if float(ladder["yaw_max"]) > 0 else "their own right"
        reasons.append(
            f"it turned the wrong way — every rung is {turned}. The prompt states the "
            "direction twice; if the clip looks correct when you watch it, the tracker's "
            "sign convention is inverted and expect_yaw_sign in the catalogue is what "
            "needs flipping."
        )
    if len(sharp) < clip.min_rungs:
        reasons.append(
            f"only {len(sharp)} sharp rungs, wanted {clip.min_rungs} — the head is not "
            "stopping for long enough. Ask for fewer steps and longer stops."
        )
    if reach < clip.min_yaw_span:
        reasons.append(
            f"the sharp frames only reach {reach:.0f} deg, wanted {clip.min_yaw_span:.0f} — "
            "the turn stopped too early. Ask for the head to end almost in profile."
        )
    if blurred_fraction > clip.max_blurred_fraction:
        reasons.append(
            f"{blurred_fraction:.0%} of rungs are motion blurred, over the "
            f"{clip.max_blurred_fraction:.0%} allowed — the head moved continuously "
            "instead of stopping."
        )

    return Verdict(not reasons, facts=facts, reasons=tuple(reasons))


def _judge_roles(clip: Clip, report: dict[str, Any]) -> Verdict:
    roles = report["roles"]
    known = set(roles.get("known", ()))
    unknown = [role for role in clip.want_roles if known and role not in known]
    if unknown:
        return Verdict(
            False,
            reasons=(f"catalogue asks for roles the engine does not have: {', '.join(unknown)}",),
            fatal=True,
        )

    covered = set(roles["covered"])
    got = [role for role in clip.want_roles if role in covered]
    short = [role for role in clip.want_roles if role not in covered]

    facts = (
        f"{len(got)} of {len(clip.want_roles)} wanted roles: "
        f"{', '.join(role.replace('source_', '') for role in got) or 'none'}",
        f"{report['usable']} usable frames of {report['frames']}",
    )
    reasons: list[str] = []
    if len(got) < clip.min_roles:
        reasons.append(
            f"only {len(got)} of the wanted roles came back, needed {clip.min_roles} — "
            f"missing {', '.join(role.replace('source_', '') for role in short)}. "
            "The expressions were held too briefly, or not reached at all."
        )
    return Verdict(not reasons, facts=facts, reasons=tuple(reasons))


def judge(clip: Clip, report: dict[str, Any]) -> Verdict:
    """Decide whether a take is worth keeping, from the extractor's report."""
    if "error" in report:
        return Verdict(False, reasons=(str(report["error"]),), fatal=True)
    if report.get("usable", 0) == 0:
        return Verdict(False, reasons=("no usable frames in the clip at all",))
    return _judge_ladder(clip, report) if clip.is_ladder else _judge_roles(clip, report)


