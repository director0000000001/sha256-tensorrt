def api_key() -> str | None:
    """The key from the environment, or from .env, which is gitignored."""
    for name in ENV_KEYS:
        value = os.environ.get(name)
        if value:
            return value.strip()

    env_file = REPO_ROOT / ".env"
    if not env_file.is_file():
        return None
    for line in env_file.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        name, _, value = stripped.partition("=")
        if name.strip() in ENV_KEYS:
            return value.strip().strip('"').strip("'")
    return None


def make_client(key: str) -> Any:
    """The SDK is a tool dependency, not a runtime one — nothing in src/ has it."""
    try:
        from google import genai
    except ImportError as exc:
        raise SystemExit(
            "The Google GenAI SDK is not installed. It is an optional extra because "
            "the application itself never calls a hosted model:\n\n"
            "    uv pip install google-genai\n"
        ) from exc

    return genai.Client(api_key=key)


def generate(
    client: Any,
    api: Api,
    model: str,
    prompt: str,
    negative: str,
    portrait: Path,
    dest: Path,
) -> None:
    """Generate one video from the portrait and write it to ``dest``.

    Image-to-video, always: text-only generation makes a different person, and
    every photograph, threshold and mask already tuned to this face becomes
    worthless.
    """
    from google.genai import types

    mime = MIME_TYPES.get(portrait.suffix.lower())
    if mime is None:
        raise RuntimeError(f"Portrait must be PNG or JPEG, not {portrait.suffix}: {portrait}")

    settings: dict[str, Any] = {
        "aspect_ratio": api.aspect_ratio,
        "resolution": api.resolution,
        "duration_seconds": api.duration_seconds,
        "person_generation": api.person_generation,
        "negative_prompt": negative,
        "number_of_videos": 1,
    }
    for name in api.drop_fields:
        settings.pop(name, None)

    try:
        config = types.GenerateVideosConfig(**settings)
    except (TypeError, ValueError) as exc:
        raise RuntimeError(
            f"The API rejected a request field: {exc}. Name it in `drop_fields` in "
            "configs/avatar_clips.toml and run again — model previews change which "
            "fields they accept."
        ) from exc

    operation = client.models.generate_videos(
        model=model,
        prompt=prompt,
        image=types.Image(image_bytes=portrait.read_bytes(), mime_type=mime),
        config=config,
    )

    deadline = time.monotonic() + api.timeout_seconds
    while not operation.done:
        if time.monotonic() > deadline:
            raise TimeoutError(
                f"No video after {api.timeout_seconds:.0f}s. The job may still finish and "
                "still be charged — check the console before generating this clip again."
            )
        time.sleep(api.poll_seconds)
        operation = client.operations.get(operation)

    if getattr(operation, "error", None):
        raise RuntimeError(f"Generation failed: {operation.error}")

    videos = getattr(operation.response, "generated_videos", None) or []
    if not videos:
        raise RuntimeError(
            "The request succeeded and returned no video. This is usually a safety "
            "filter on a real face — check `person_generation` in the catalogue."
        )

    dest.parent.mkdir(parents=True, exist_ok=True)
    video = videos[0].video
    client.files.download(file=video)
    video.save(str(dest))
    if not dest.is_file() or dest.stat().st_size == 0:
        raise RuntimeError(f"Nothing was written to {dest}.")


def list_models(client: Any) -> None:
    """What this key can actually reach, so the catalogue can be corrected."""
    print("Video models visible to this key:\n")
    found = False
    for model in client.models.list():
        name = str(getattr(model, "name", ""))
        if "veo" not in name.lower():
            continue
        found = True
        actions = getattr(model, "supported_actions", None) or []
        print(f"  {name}   {' '.join(actions)}")
    if not found:
        print("  none — this key has no Veo access, or the models are named differently.")


