@dataclass
class Ledger:
    """What has been spent, written the moment it is spent.

    Priced from the catalogue rather than from a bill, so it is an estimate of
    the account's own numbers. It counts only what this tool sent.
    """

    path: Path
    rows: list[dict[str, Any]] = field(default_factory=list)

    @classmethod
    def load(cls, path: Path) -> Ledger:
        if path.is_file():
            data = json.loads(path.read_text(encoding="utf-8"))
            return cls(path=path, rows=list(data.get("attempts", [])))
        return cls(path=path, rows=[])

    @property
    def total_usd(self) -> float:
        return sum(float(row.get("usd", 0.0)) for row in self.rows)

    def attempts(self, clip_id: str, tier: str) -> int:
        return sum(1 for row in self.rows if row["clip"] == clip_id and row["tier"] == tier)

    def passed(self, clip_id: str) -> bool:
        return any(
            row["clip"] == clip_id and row["tier"] == "final" and row.get("ok") for row in self.rows
        )

    def record(self, **row: Any) -> None:
        row.setdefault("at", datetime.now(UTC).isoformat(timespec="seconds"))
        self.rows.append(row)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text(
            json.dumps({"attempts": self.rows}, indent=2, ensure_ascii=False), encoding="utf-8"
        )


