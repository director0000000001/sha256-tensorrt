def measure(video: Path, work: Path, clip: Clip, portrait: Path) -> tuple[Verdict, dict[str, Any]]:
    """Run the extractor over a clip and judge its report."""
    frames = work / f"{video.stem}-frames"
    report_path = work / f"{video.stem}-report.json"
    command = [
        sys.executable,
        str(REPO_ROOT / "scripts" / "extract_avatar_frames.py"),
        str(video),
        "--base",
        str(portrait),
        "--out",
        str(frames),
        "--report",
        str(report_path),
    ]
    if clip.is_ladder:
        command.append("--ladder")

    print(f"  measuring: {' '.join(command[1:])}")
    completed = subprocess.run(command, check=False)

    if not report_path.is_file():
        return (
            Verdict(
                False,
                reasons=(
                    f"the extractor wrote no report (exit {completed.returncode}). Its output "
                    "is above; this is a broken checkout, not a bad clip.",
                ),
                fatal=True,
            ),
            {},
        )

    report = json.loads(report_path.read_text(encoding="utf-8"))
    return judge(clip, report), report


def cannot_measure() -> str | None:
    """Why the measurement would fail, checked before any money is spent.

    A clip that cannot be measured is a clip bought blind, which is the whole
    thing this tool exists to stop. Both of these are one command to fix and
    neither is visible until the first video has already been paid for.
    """
    if importlib.util.find_spec("mediapipe") is None:
        return (
            "MediaPipe is not installed, so the frames could not be measured.\n"
            "    uv pip install mediapipe --no-deps  (see pyproject for why --no-deps)"
        )

    sys.path.insert(0, str(REPO_ROOT / "src"))
    try:
        from sha256.tracking.mediapipe_tracker import DEFAULT_MODEL_RELATIVE_PATH
    except ImportError:
        return None  # Not knowable from here; the first measurement will say so.

    model = REPO_ROOT / "models" / DEFAULT_MODEL_RELATIVE_PATH
    if not model.is_file():
        return (
            f"The face landmarker bundle is missing: {model}\n"
            "    uv run python scripts/fetch_face_landmarker.py"
        )
    return None


