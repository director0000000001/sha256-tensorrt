"""Generate the avatar source clips, and measure each one before paying again.

Every clip so far has been generated by hand, watched, and judged days later by
what the avatar looked like on a call. Two were paid for twice — the first turn
clip swept continuously and every rung of the ladder built from it is a smear;
the second was asked for both directions and came back turning only one way.
Neither failure was visible at the moment it was bought.

This closes that loop. For each clip in ``configs/avatar_clips.toml`` it

1.  generates the video from the portrait, with the prompt held as data;
2.  runs it straight through ``extract_avatar_frames.py --report``, which is
    the same measurement the engine's own selector makes;
3.  reads the report and says plainly whether the take is usable;
4.  regenerates **only** when the measurement failed, up to a bounded number of
    attempts.

**Money is the constraint, so money is the interface.** Every request is priced
before it is sent, refused if it would cross ``--budget``, and written to a
ledger the moment it returns — a crash must not lose the record of what was
spent. ``--plan`` prices the whole run without sending anything.

**A probe is a prompt test, not a preview.** Turn clips generate once on the
cheap model first, because what has failed twice is the generator *following
the prompt* — the direction, and whether it stops. That is visible in a probe
at a third of the price. It is not a preview of the final take: a different
model produces different motion, and the sharp frames still have to come from
the quality model.

Usage::

    python scripts/generate_avatar_clips.py --plan
    python scripts/generate_avatar_clips.py --all --budget 50
    python scripts/generate_avatar_clips.py --clip turn-frame-right
    python scripts/generate_avatar_clips.py --print-prompt turn-frame-right
    python scripts/generate_avatar_clips.py --list-models

The API key comes from ``GEMINI_API_KEY`` or ``GOOGLE_API_KEY``, in the
environment or in ``.env`` at the repo root. ``.env`` is gitignored; the key
must never be committed.
"""

