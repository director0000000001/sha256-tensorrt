def readable(path: Path) -> str:
    """Repo-relative where that is shorter, absolute where it is not.

    ``--out`` may point anywhere, including another drive, and a ledger write
    is the last thing that should fail after a video has been paid for.
    """
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def announce(verdict: Verdict) -> None:
    for fact in verdict.facts:
        print(f"    {fact}")
    if verdict.ok:
        print("  USABLE.")
        return
    for reason in verdict.reasons:
        print(f"  NOT USABLE: {reason}")


def run_clip(
    clip: Clip,
    api: Api,
    negative: str,
    client: Any,
    ledger: Ledger,
    args: argparse.Namespace,
) -> str:
    """Generate one clip until it measures usable or the allowance runs out.

    Returns one of ``passed``, ``failed``, ``skipped``, ``budget``, ``fatal``.
    """
    print(f"\n=== {clip.id} — {clip.title}")

    if ledger.passed(clip.id) and not args.force:
        print("  already generated and measured usable. --force to do it again.")
        return "skipped"

    work = args.out / clip.id
    tiers = ["probe", "final"] if clip.probe_first and not args.no_probe else ["final"]

    for tier in tiers:
        for attempt in range(1, args.max_attempts + 1):
            cost = api.cost(tier)
            if ledger.total_usd + cost > args.budget:
                print(
                    f"  STOPPING: this {tier} take costs ${cost:.2f} and the ledger is at "
                    f"${ledger.total_usd:.2f} of a ${args.budget:.2f} budget."
                )
                return "budget"

            index = ledger.attempts(clip.id, tier) + 1
            video = work / f"{tier}-{index}.mp4"
            print(
                f"  {tier} take {attempt}/{args.max_attempts} on {api.model(tier)} "
                f"— ${cost:.2f}, ledger ${ledger.total_usd:.2f}/${args.budget:.2f}"
            )

            try:
                generate(client, api, api.model(tier), clip.prompt, negative, args.portrait, video)
            except Exception as exc:
                print(f"  REQUEST FAILED: {exc}")
                ledger.record(
                    clip=clip.id,
                    tier=tier,
                    model=api.model(tier),
                    usd=0.0,
                    ok=False,
                    error=str(exc),
                    video=None,
                )
                return "fatal"

            verdict, report = measure(video, work, clip, args.portrait)
            ledger.record(
                clip=clip.id,
                tier=tier,
                model=api.model(tier),
                usd=round(cost, 4),
                ok=verdict.ok,
                video=readable(video),
                facts=list(verdict.facts),
                reasons=list(verdict.reasons),
                usable_frames=report.get("usable"),
            )
            announce(verdict)

            if verdict.fatal:
                print("  This stops the run — nothing here is fixed by generating again.")
                return "fatal"
            if verdict.ok:
                break
        else:
            print(
                f"  {clip.id}: {args.max_attempts} {tier} takes and none usable. "
                "The prompt is what has to change now, not the number of attempts."
            )
            return "failed"

    return "passed"


def plan(clips: list[Clip], api: Api, args: argparse.Namespace, ledger: Ledger) -> float:
    """Price the run without sending anything."""
    print(f"\n{'clip':<20}{'check':<9}{'takes':<26}{'worst case':>11}")
    worst = 0.0
    for clip in clips:
        tiers = ["probe", "final"] if clip.probe_first and not args.no_probe else ["final"]
        cost = sum(api.cost(tier) * args.max_attempts for tier in tiers)
        worst += cost
        takes = " + ".join(f"{args.max_attempts}x {tier}" for tier in tiers)
        print(f"{clip.id:<20}{clip.check:<9}{takes:<26}{'$' + format(cost, '.2f'):>11}")

    best = sum(
        api.cost("probe") + api.cost("final")
        if clip.probe_first and not args.no_probe
        else api.cost("final")
        for clip in clips
    )
    print(f"\n  everything first time:  ${best:.2f}")
    print(f"  every take retried:     ${worst:.2f}")
    print(f"  already spent:          ${ledger.total_usd:.2f}   (this tool only)")
    print(f"  budget:                 ${args.budget:.2f}")
    print(
        f"\n  Prices come from configs/avatar_clips.toml "
        f"(${api.usd_per_second_final:.2f}/s final, ${api.usd_per_second_probe:.2f}/s probe, "
        f"{api.duration_seconds}s each). Check them against the billing page."
    )
    return worst


def confirm(prompt: str) -> bool:
    if not sys.stdin.isatty():
        print(f"{prompt} — not a terminal, so pass --yes to go ahead.")
        return False
    return input(f"{prompt} [y/N] ").strip().lower() in {"y", "yes"}


def main(argv: list[str] | None = None) -> int:
    # A Windows console in a legacy codepage raises on the first em dash. That
    # would be a crash *after* a video was paid for, losing the verdict and the
    # path to the file, so characters it cannot draw become question marks.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalogue", type=Path, default=DEFAULT_CATALOGUE)
    parser.add_argument("--portrait", type=Path, default=DEFAULT_PORTRAIT)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--clip", action="append", default=[], help="Clip id; repeatable.")
    parser.add_argument("--all", action="store_true", help="Every clip that is not parked.")
    parser.add_argument(
        "--include-parked",
        action="store_true",
        help="Also generate clips the engine cannot use yet. Read their `why` first.",
    )
    parser.add_argument(
        "--budget",
        type=float,
        default=DEFAULT_BUDGET_USD,
        help="Hard ceiling in USD across the whole ledger, not per run.",
    )
    parser.add_argument("--max-attempts", type=int, default=DEFAULT_MAX_ATTEMPTS)
    parser.add_argument("--no-probe", action="store_true", help="Skip the cheap prompt test.")
    parser.add_argument("--force", action="store_true", help="Regenerate a clip that passed.")
    parser.add_argument("--yes", action="store_true", help="Do not ask before spending.")
    parser.add_argument("--plan", action="store_true", help="Price the run and stop.")
    parser.add_argument("--list", action="store_true", help="List the catalogue and stop.")
    parser.add_argument("--print-prompt", metavar="ID", help="Print one composed prompt and stop.")
    parser.add_argument("--list-models", action="store_true", help="Ask the API what it offers.")
    args = parser.parse_args(argv)

    api, catalogue = load_catalogue(args.catalogue)
    negative = negative_prompt(args.catalogue)
    ledger = Ledger.load(args.out / "ledger.json")
    by_id = {clip.id: clip for clip in catalogue}

    if args.list:
        print(f"{'clip':<20}{'order':>6}  {'check':<8}title")
        for clip in catalogue:
            mark = "  [parked]" if clip.parked else ""
            print(f"{clip.id:<20}{clip.order:>6}  {clip.check:<8}{clip.title}{mark}")
            if clip.why:
                print(f"{'':<36}{clip.why}")
        return 0

    if args.print_prompt:
        clip = by_id.get(args.print_prompt)
        if clip is None:
            print(f"No such clip: {args.print_prompt}")
            return 1
        print(clip.prompt)
        print(f"\n--- negative prompt ---\n{negative}")
        return 0

    if args.list_models:
        key = api_key()
        if not key:
            print(f"No API key. Set one of {', '.join(ENV_KEYS)} in the environment or .env.")
            return 1
        list_models(make_client(key))
        return 0

    if args.clip:
        unknown = [name for name in args.clip if name not in by_id]
        if unknown:
            print(f"No such clip: {', '.join(unknown)}. Try --list.")
            return 1
        selected = [by_id[name] for name in args.clip]
    elif args.all:
        selected = [clip for clip in catalogue if args.include_parked or not clip.parked]
        parked = [clip for clip in catalogue if clip.parked and not args.include_parked]
        if parked:
            names = ", ".join(clip.id for clip in parked)
            print(f"Parked, not generating: {names}  (--include-parked to override)")
    else:
        parser.error("Choose --clip ID, or --all. --plan and --list spend nothing.")

    if not args.portrait.is_file():
        print(f"Portrait not found: {args.portrait}")
        return 1

    worst = plan(selected, api, args, ledger)
    if args.plan:
        return 0

    if ledger.total_usd + worst > args.budget:
        print(
            f"\n  Note: the worst case is over budget. The run will stop cleanly when the "
            f"next take would cross ${args.budget:.2f}, having generated what fitted."
        )

    key = api_key()
    if not key:
        print(f"\nNo API key. Set one of {', '.join(ENV_KEYS)} in the environment or .env.")
        return 1

    blocked = cannot_measure()
    if blocked:
        print(f"\nNot spending anything yet — the clips could not be measured:\n\n  {blocked}\n")
        return 1

    if not args.yes and not confirm(f"\nGenerate {len(selected)} clip(s) with real money?"):
        print("Nothing sent.")
        return 1

    client = make_client(key)
    outcomes: dict[str, str] = {}
    for clip in selected:
        outcome = run_clip(clip, api, negative, client, ledger, args)
        outcomes[clip.id] = outcome
        if outcome in {"budget", "fatal"}:
            break

    print(f"\n{'clip':<20}outcome")
    for clip in selected:
        print(f"{clip.id:<20}{outcomes.get(clip.id, 'not reached')}")
    print(f"\nSpent by this tool, all runs: ${ledger.total_usd:.2f} of ${args.budget:.2f}")
    print(f"Ledger: {ledger.path}")

    if any(
        outcomes.get(clip.id) == "passed" for clip in selected if clip.is_ladder
    ):  # pragma: no cover - reporting only
        print(
            "\nA turn clip passed. Before pasting its rungs into the avatar's metadata.json,\n"
            "DELETE every existing turn_*.png entry from the assets list: they are the\n"
            "motion-blurred rungs, and a blurred rung is chosen by angle exactly like a\n"
            "sharp one. The new entries are in each clip's *-frames/ladder_assets.json."
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
