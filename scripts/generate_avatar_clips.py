@dataclass(frozen=True)
class Api:
    """Everything about the service that is a number rather than a decision."""

    model_final: str
    model_probe: str
    usd_per_second_final: float
    usd_per_second_probe: float
    duration_seconds: int
    resolution: str
    aspect_ratio: str
    person_generation: str
    poll_seconds: float
    timeout_seconds: float
    drop_fields: tuple[str, ...]

    def model(self, tier: str) -> str:
        return self.model_probe if tier == "probe" else self.model_final

    def usd_per_second(self, tier: str) -> float:
        return self.usd_per_second_probe if tier == "probe" else self.usd_per_second_final

    def cost(self, tier: str) -> float:
        return self.usd_per_second(tier) * self.duration_seconds


@dataclass(frozen=True)
class Clip:
    """One clip: the prompt that makes it and the measurement that accepts it."""

    id: str
    order: int
    title: str
    why: str
    check: str
    prompt: str
    parked: bool = False
    probe_first: bool = False
    # check == "ladder"
    min_rungs: int = 5
    min_yaw_span: float = 25.0
    max_blurred_fraction: float = 0.34
    expect_yaw_sign: str = "any"
    # check == "roles"
    want_roles: tuple[str, ...] = ()
    min_roles: int = 1

    @property
    def is_ladder(self) -> bool:
        return self.check == "ladder"


def load_catalogue(path: Path) -> tuple[Api, list[Clip]]:
    """Read the clips and the service settings out of TOML."""
    raw = tomllib.loads(path.read_text(encoding="utf-8"))
    api_raw = raw["api"]
    api = Api(
        model_final=api_raw["model_final"],
        model_probe=api_raw["model_probe"],
        usd_per_second_final=float(api_raw["usd_per_second_final"]),
        usd_per_second_probe=float(api_raw["usd_per_second_probe"]),
        duration_seconds=int(api_raw["duration_seconds"]),
        resolution=api_raw["resolution"],
        aspect_ratio=api_raw["aspect_ratio"],
        person_generation=api_raw["person_generation"],
        poll_seconds=float(api_raw.get("poll_seconds", 15.0)),
        timeout_seconds=float(api_raw.get("timeout_seconds", 900.0)),
        drop_fields=tuple(api_raw.get("drop_fields", ())),
    )

    shared = raw["defaults"]["shared"].strip()
    clips: list[Clip] = []
    for entry in raw["clip"]:
        body = entry["body"].strip()
        clips.append(
            Clip(
                id=entry["id"],
                order=int(entry["order"]),
                title=entry["title"],
                why=entry.get("why", ""),
                check=entry["check"],
                prompt=f"{body}\n\n{shared}",
                parked=bool(entry.get("parked", False)),
                probe_first=bool(entry.get("probe_first", False)),
                min_rungs=int(entry.get("min_rungs", 5)),
                min_yaw_span=float(entry.get("min_yaw_span", 25.0)),
                max_blurred_fraction=float(entry.get("max_blurred_fraction", 0.34)),
                expect_yaw_sign=entry.get("expect_yaw_sign", "any"),
                want_roles=tuple(entry.get("want_roles", ())),
                min_roles=int(entry.get("min_roles", 1)),
            )
        )
    clips.sort(key=lambda clip: clip.order)
    return api, clips


def negative_prompt(path: Path) -> str:
    raw = tomllib.loads(path.read_text(encoding="utf-8"))
    return " ".join(raw["defaults"]["negative_prompt"].split())


